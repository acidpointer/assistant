//! Transport-independent durable operation contracts. Only an owner capability
//! grants access; these payloads never manufacture authority. Host-provided
//! timestamps and capture policy preserve attribution without retaining hidden
//! reasoning or ephemeral tool data. Private prose uses [`MemoryText`].

use super::{
    Claim, MemoryError, MemoryId, MemoryResult, MemoryText, OperationKey, Revision, Source,
};
use serde::{Deserialize, Serialize};

/// Stable client identity across reconnects and daemon instances.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(try_from = "[String; 3]", into = "[String; 3]")]
pub struct ClientRequestKey([String; 3]);
impl ClientRequestKey {
    /// Validate three opaque identity components, independently of authentication.
    /// # Errors
    /// Rejects empty, oversized or non-opaque components.
    pub fn new(
        namespace: impl Into<String>,
        client: impl Into<String>,
        request: impl Into<String>,
    ) -> MemoryResult<Self> {
        Self::try_from([namespace.into(), client.into(), request.into()])
    }
    pub(super) fn storage_key(&self) -> MemoryResult<OperationKey> {
        use sha2::{Digest, Sha256};
        let digest = Sha256::digest(serde_json::to_vec(&(1_u8, &self.0))?);
        OperationKey::new("product", format!("{digest:x}"))
    }
}
impl TryFrom<[String; 3]> for ClientRequestKey {
    type Error = MemoryError;
    fn try_from(parts: [String; 3]) -> MemoryResult<Self> {
        for part in &parts {
            OperationKey::new("client", part)?;
        }
        Ok(Self(parts))
    }
}
impl From<ClientRequestKey> for [String; 3] {
    fn from(key: ClientRequestKey) -> Self {
        key.0
    }
}

/// Admitted worst-case output bounds; lowering configuration cannot revoke them.
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
#[serde(try_from = "(u32, u16, u32)", into = "(u32, u16, u32)")]
pub struct OperationLimits {
    pub(super) assistant_bytes: u32,
    pub(super) tool_calls: u16,
    pub(super) receipt_bytes: u32,
}
impl OperationLimits {
    /// Reserve bounded assistant output and tool argument/result payloads.
    /// # Errors
    /// Rejects zero/oversized messages, over 32 tools or receipts over 16 KiB.
    pub fn new(assistant_bytes: u32, tool_calls: u16, receipt_bytes: u32) -> MemoryResult<Self> {
        if !(1..=131_072).contains(&assistant_bytes)
            || tool_calls > 32
            || !(1..=16_384).contains(&receipt_bytes)
        {
            return Err(MemoryError::InvalidInput("operation limits"));
        }
        Ok(Self {
            assistant_bytes,
            tool_calls,
            receipt_bytes,
        })
    }
    pub(super) fn reservation(self, input_bytes: usize) -> MemoryResult<u64> {
        // Eight times bounded serialized prose covers JSON escaping, replay/source
        // copies and FTS. Per-command page allowance also covers small receipts.
        // This conservative soft reservation cannot defeat external disk exhaustion.
        let input = u64::try_from(input_bytes).map_err(|_| MemoryError::Capacity)?;
        Ok(8 * (input
            + u64::from(self.assistant_bytes)
            + 2 * u64::from(self.tool_calls) * u64::from(self.receipt_bytes))
            + (4 + 2 * u64::from(self.tool_calls)) * 65_536)
    }
}
impl TryFrom<(u32, u16, u32)> for OperationLimits {
    type Error = MemoryError;
    fn try_from(v: (u32, u16, u32)) -> MemoryResult<Self> {
        Self::new(v.0, v.1, v.2)
    }
}
impl From<OperationLimits> for (u32, u16, u32) {
    fn from(v: OperationLimits) -> Self {
        (v.assistant_bytes, v.tool_calls, v.receipt_bytes)
    }
}

/// Literal input and bounded reservation committed before product acceptance.
#[derive(Debug, Clone, Serialize)]
pub struct OperationAdmission {
    /// Reused after a timeout, never regenerated by a transport retry.
    pub key: ClientRequestKey,
    /// Exact visible user input, at most 16 KiB.
    pub input: MemoryText,
    /// Host-observed UTC milliseconds, not inferred event/valid time.
    pub observed_at: i64,
    /// Immutable bounds for later required writes.
    pub limits: OperationLimits,
}

/// Immutable source identity; possession is not authority.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct SourceRef {
    /// Source identity.
    pub id: MemoryId,
    /// Exact source revision.
    pub revision: Revision,
}

/// Durable product state, independent of in-memory display/run revisions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum OperationState {
    /// Input and settlement reservation committed.
    Accepted,
    /// Execution began; unfinished work recovers as interrupted.
    Running,
    /// Confirmed successful terminal outcome.
    Completed,
    /// Cancelled after acceptance; input remains durable.
    Cancelled,
    /// Confirmed failure.
    Failed,
    /// Lost execution; tools are never automatically replayed.
    Interrupted,
}

/// Inspectable operation projection without copying input/output prose.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct OperationRecord {
    /// Stable operation identity.
    pub id: MemoryId,
    /// Revision of persisted execution state.
    pub revision: Revision,
    /// Current persisted state.
    pub state: OperationState,
    /// Original accepted user source.
    pub input: SourceRef,
    /// Persisted visible assistant output, if any.
    pub assistant: Option<SourceRef>,
    /// At least one invocation lacks a confirmed outcome.
    pub unknown_tool_outcome: bool,
}

/// Host-selected terminal state; an active state cannot be supplied here.
#[derive(Debug, Clone, Copy, Serialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum TerminalOutcome {
    /// Finished successfully.
    Completed,
    /// User/runtime cancellation after acceptance.
    Cancelled,
    /// Confirmed execution failure.
    Failed,
    /// Interrupted execution or uncertain external effect.
    Interrupted,
}

/// Bounded visible output and terminal status. Hidden reasoning is not accepted.
#[derive(Debug, Clone, Serialize)]
pub struct OperationFinalization {
    /// Terminal execution outcome.
    pub outcome: TerminalOutcome,
    /// Visible final/partial assistant output only.
    pub assistant: Option<MemoryText>,
}

/// Declared tool effect class, retained even for ephemeral tools.
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum ToolEffect {
    /// No external state mutation.
    ReadOnly,
    /// External state may change; interruption may be uncertain.
    External,
}

/// Capture selection before serialization. Ephemeral tools accept no raw arguments.
#[derive(Debug, Clone, Serialize)]
#[non_exhaustive]
pub enum ToolCapture {
    /// Keep identity/state only.
    Ephemeral,
    /// Retain bounded host-approved arguments.
    Retained {
        /// Exact retained argument serialization.
        arguments: MemoryText,
    },
}

/// Host-validated dispatch identity, persisted before calling the actual handler.
#[derive(Debug, Clone, Serialize)]
pub struct ToolIntent {
    /// One-based host ordinal unique within the operation.
    pub ordinal: u16,
    /// Registered handler name, never executable code or shell text.
    pub handler: String,
    /// Host-declared effect class.
    pub effect: ToolEffect,
    /// Host-declared capture policy.
    pub capture: ToolCapture,
}

/// Known tool result or explicit uncertainty; pending intent is not a completion.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum ToolOutcome {
    /// Handler returned success.
    Succeeded,
    /// Handler returned a confirmed failure.
    Failed,
    /// No confirmed result; effects may have happened.
    Unknown,
}

/// Minimal durable invocation view. Raw ephemeral results cannot enter this type.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolInvocation {
    /// Stable parent operation identity.
    pub operation_id: MemoryId,
    /// Host ordinal.
    pub ordinal: u16,
    /// Registered handler.
    pub handler: String,
    /// Declared effect class.
    pub effect: ToolEffect,
    /// None while only intent is committed.
    pub outcome: Option<ToolOutcome>,
    /// Source of a retained tool result, if any.
    pub result: Option<SourceRef>,
}

/// Host attribution; assistant/tool statements do not corroborate user facts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum SourceRole {
    /// Literal user statement.
    User,
    /// Visible assistant statement or promise.
    Assistant,
    /// Captured tool data.
    Tool,
}

/// Formation state independent of literal source durability and index coverage.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum FormationState {
    /// Durable pending/leased formation.
    Queued,
    /// Literal saved; optional job quota prevented scheduling.
    Deferred,
    /// Host reported complete examination.
    Complete,
    /// No qualified interpretation within allowance.
    Unresolved,
    /// No formation requested for this source.
    NotApplicable,
}

/// Literal evidence plus non-model-selectable attribution and work state.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SourceRecord {
    /// Owned literal source.
    pub source: Source,
    /// Host-supplied speaker/data class.
    pub role: SourceRole,
    /// Associated product operation, absent for standalone explicit memories.
    pub operation_id: Option<MemoryId>,
    /// Observed UTC milliseconds; null when not recorded.
    pub observed_at: Option<i64>,
    /// Structuring state, separate from saved/indexed state.
    pub formation: FormationState,
}

/// Explicitly paginated assertion history.
#[derive(Debug, Clone)]
pub struct ClaimHistoryPage {
    /// Eligible versions after the supplied revision, in revision order.
    pub claims: Vec<Claim>,
    /// Last returned revision when another eligible page exists.
    pub next_after: Option<Revision>,
}

/// Storage availability only; semantic/model qualification is a separate component.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum StorageStatus {
    /// Ordinary admission is available.
    Ready,
    /// Ordinary growth is blocked; critical settlement remains possible.
    CapacityBlocked,
    /// A required writer failure needs owner recovery/reopen.
    Blocked,
}

/// Bounded operational counters without private text or paths.
#[derive(Debug, Clone)]
pub struct StorageHealth {
    /// Current admission state.
    pub status: StorageStatus,
    /// Direct storage files, including WAL and journal.
    pub used_bytes: u64,
    /// Configured combined soft quota.
    pub quota_bytes: u64,
    /// Outstanding worst-case operation settlement reservations.
    pub reserved_bytes: u64,
    /// Ready/leased jobs.
    pub pending_jobs: u64,
    /// Saved sources awaiting optional job capacity.
    pub deferred_sources: u64,
}

/// Whether event retention must preserve a consumer's unprocessed events.
#[derive(Debug, Clone, Copy, Serialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum ConsumerRequirement {
    /// Participates in retention low watermark.
    Required,
    /// May be rebuilt if event history is compacted.
    Optional,
}

/// Persisted causal change signal; source payloads are resolved through authority.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryChange {
    /// Monotonic committed change sequence.
    pub sequence: Revision,
    /// Registered host change class.
    pub kind: String,
    /// Root command identity; derived work must retain it.
    pub root_cause: MemoryId,
}

/// Short event snapshot, copied without holding a read transaction during work.
#[derive(Debug, Clone)]
pub struct EventPage {
    /// Persisted consumer position at snapshot time.
    pub after: Option<Revision>,
    /// At most 32 events.
    pub events: Vec<MemoryChange>,
    /// More eligible events existed in the snapshot.
    pub truncated: bool,
}
